// 从 orval 生成的 tags-split 目录结构推导 Controller 绑定层:
// 每个生成的 tag 目录(如 generated/system/system.ts)对应一行
// `export const SystemController = getSystem();`
// 由 gen:api 流水线调用(orval 之后执行);输出文件禁止手改。
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const generatedDir = fileURLToPath(new URL("../src/api/generated", import.meta.url));
const outFile = fileURLToPath(new URL("../src/api/controllers.gen.ts", import.meta.url));

const pascal = (name) =>
  name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const tagDirs = readdirSync(generatedDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

if (tagDirs.length === 0) {
  console.error("no generated tag directories found under", generatedDir);
  process.exit(1);
}

let imports = "";
let bindings = "";
for (const tag of tagDirs) {
  const pascalTag = pascal(tag);
  const moduleFile = path.join(generatedDir, tag, `${tag}.ts`);
  if (!existsSync(moduleFile)) {
    console.error(`unexpected generated layout: missing ${moduleFile}`);
    process.exit(1);
  }
  imports += `import { get${pascalTag} } from "./generated/${tag}/${tag}";\n`;
  bindings += `export const ${pascalTag}Controller = get${pascalTag}();\n`;
}

const header = `// Generated by scripts/generate-controllers.mjs — 禁止手改。
// 绑定层:把 orval 按 tag 生成的工厂函数实例化为单例,页面统一 XxxController.xxx() 调用。

`;

writeFileSync(outFile, header + imports + "\n" + bindings);
console.info(
  `controllers.gen.ts written with ${tagDirs.length} controllers: ${tagDirs.join(", ")}`
);
